/**
 * @file Generates exact declaration locations for authored TypeScript, JavaScript, Astro, and CSS.
 * Functions: collectFiles, symbolsForFile, renderIndex, main.
 * Variables: ROOT, OUTPUT, CODE_EXTENSIONS, EXCLUDED_DIRECTORIES, checkOnly.
 * Line locations: this script indexes itself in docs/CODE_INDEX.md.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "docs", "CODE_INDEX.md");
const CODE_EXTENSIONS = new Set([".astro", ".css", ".js", ".mjs", ".ts"]);
const EXCLUDED_DIRECTORIES = new Set([
  ".astro",
  ".git",
  ".runtime",
  "coverage",
  "dist",
  "node_modules",
  "playwright-report",
  "test-results",
]);
const checkOnly = process.argv.includes("--check");

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const results = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    if (EXCLUDED_DIRECTORIES.has(entry.name)) continue;
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) results.push(...(await collectFiles(absolute)));
    else if (CODE_EXTENSIONS.has(path.extname(entry.name)))
      results.push(path.relative(ROOT, absolute).replaceAll("\\", "/"));
  }
  return results;
}

function symbolsForFile(source) {
  const patterns = [
    { kind: "function", expression: /^(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/u },
    { kind: "class", expression: /^(?:export\s+)?class\s+([A-Za-z_$][\w$]*)/u },
    { kind: "variable", expression: /^(?:export\s+)?(?:const|let|var)\s+([A-Za-z_$][\w$]*)/u },
    { kind: "custom property", expression: /^(--[a-z0-9-]+)\s*:/u },
  ];
  const symbols = [];
  source.split(/\r?\n/u).forEach((line, index) => {
    const trimmed = line.trim();
    for (const pattern of patterns) {
      const match = pattern.expression.exec(trimmed);
      if (match?.[1]) {
        symbols.push({ line: index + 1, kind: pattern.kind, name: match[1] });
        break;
      }
    }
  });
  return symbols;
}

function renderIndex(records) {
  const lines = [
    "# Code index",
    "",
    "> Generated by `npm run code-index`. Locations are one-based and are the authority referenced by source headers.",
    "",
  ];
  for (const record of records) {
    lines.push(`## \`${record.file}\``, "", "| Line | Kind | Symbol |", "| ---: | --- | --- |");
    if (record.symbols.length === 0) lines.push("| — | file | No declarations indexed |");
    else
      for (const symbol of record.symbols)
        lines.push(`| ${symbol.line} | ${symbol.kind} | \`${symbol.name}\` |`);
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

async function main() {
  const files = await collectFiles(ROOT);
  const records = [];
  for (const file of files)
    records.push({ file, symbols: symbolsForFile(await readFile(path.join(ROOT, file), "utf8")) });
  const rendered = renderIndex(records);
  if (checkOnly) {
    if ((await readFile(OUTPUT, "utf8")) !== rendered)
      throw new Error("docs/CODE_INDEX.md is stale; run npm run code-index.");
    console.log(`Code index is current for ${records.length} files.`);
  } else {
    await writeFile(OUTPUT, rendered, "utf8");
    console.log(`Indexed ${records.length} files in ${path.relative(ROOT, OUTPUT)}.`);
  }
}

await main();
