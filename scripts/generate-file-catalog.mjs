/**
 * @file Generates a complete repository file catalog from source headers and curated fallbacks.
 * Functions: collectFiles, extractDescription, describeFile, renderCatalog, main.
 * Variables: ROOT, OUTPUT, EXCLUDED_DIRECTORIES, STATIC_DESCRIPTIONS, checkOnly.
 * Line locations: see docs/CODE_INDEX.md for the generated symbol index.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "docs", "FILE_CATALOG.md");
const EXCLUDED_DIRECTORIES = new Set([
  ".astro",
  ".git",
  ".runtime",
  "coverage",
  "dist",
  "node_modules",
  "playwright-report",
  "test-results",
]);
const checkOnly = process.argv.includes("--check");
const STATIC_DESCRIPTIONS = new Map([
  [".editorconfig", "Editor-neutral whitespace, encoding, and newline policy."],
  [".gitattributes", "Cross-platform line-ending and binary-file policy."],
  [".gitignore", "Generated dependency, build, coverage, browser, and runtime exclusions."],
  [".prettierignore", "Files intentionally excluded from automated formatting."],
  [".prettierrc.json", "Repository formatting policy, including Astro parsing."],
  ["LICENSE", "MIT license terms."],
  ["package.json", "Pinned runtime, toolchain, scripts, and reviewed install-script policy."],
  ["package-lock.json", "Exact npm dependency graph for deterministic installation."],
  ["tsconfig.json", "Strictest Astro and TypeScript compiler policy."],
  ["public/manifest.webmanifest", "Browser metadata and repository-scoped launch URL."],
  ["public/favicon.svg", "High-contrast JS monogram favicon."],
  ["public/images/portfolio-preview.svg", "Social preview artwork for shared portfolio links."],
  [
    "src/data/github-repositories.json",
    "Reviewed GitHub repository metadata cache used by offline builds.",
  ],
]);

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const results = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    if (EXCLUDED_DIRECTORIES.has(entry.name)) continue;
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) results.push(...(await collectFiles(absolute)));
    else results.push(path.relative(ROOT, absolute).replaceAll("\\", "/"));
  }
  return results;
}

function extractDescription(source) {
  const fileTag = source.match(/@file\s+([^\r\n*]+)/u)?.[1]?.trim();
  if (fileTag) return fileTag;
  const fileLine = source.match(/(?:File:|# File:)\s*([^\r\n]+)/u)?.[1]?.trim();
  if (!fileLine) return null;
  const withoutEnd = fileLine.endsWith("--!>")
    ? fileLine.slice(0, -4)
    : fileLine.endsWith("-->")
      ? fileLine.slice(0, -3)
      : fileLine;
  return withoutEnd.trim();
}

function describeFile(file, source) {
  const staticDescription = STATIC_DESCRIPTIONS.get(file);
  if (staticDescription) return staticDescription;
  const extracted = extractDescription(source);
  if (extracted) return extracted;
  if (file === "README.md")
    return "Project overview, quick start, features, evidence, and repository map.";
  if (file === "SECURITY.md")
    return "Supported versions, reporting process, and public-data policy.";
  if (file === "CONTRIBUTING.md")
    return "Contributor workflow, quality gates, and content expectations.";
  if (file.endsWith(".md")) return "Project documentation described by its title and sections.";
  if (file.endsWith(".yml") || file.endsWith(".yaml"))
    return "Automated repository workflow or dependency policy.";
  return "Repository support file.";
}

function renderCatalog(records) {
  const lines = [
    "# File catalog",
    "",
    "> Generated by `npm run file-catalog`. Dependency, build, coverage, and browser-report directories are excluded.",
    "",
    "| File | Purpose |",
    "| --- | --- |",
  ];
  for (const record of records)
    lines.push(`| \`${record.file}\` | ${record.description.replaceAll("|", "\\|")} |`);
  return `${lines.join("\n")}\n`;
}

async function main() {
  const files = await collectFiles(ROOT);
  const records = [];
  for (const file of files)
    records.push({
      file,
      description: describeFile(file, await readFile(path.join(ROOT, file), "utf8")),
    });
  const rendered = await format(renderCatalog(records), { parser: "markdown" });
  if (checkOnly) {
    if ((await readFile(OUTPUT, "utf8")) !== rendered)
      throw new Error("docs/FILE_CATALOG.md is stale; run npm run file-catalog.");
    console.log(`File catalog is current for ${records.length} files.`);
  } else {
    await writeFile(OUTPUT, rendered, "utf8");
    console.log(`Cataloged ${records.length} files in ${path.relative(ROOT, OUTPUT)}.`);
  }
}

await main();
